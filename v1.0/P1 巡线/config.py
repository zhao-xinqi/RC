"""
P1 巡线 - 可配置参数

所有参数集中管理, 便于后续根据实际水下环境调优.
参数分为三组:
  1. 预处理参数  - 图像缩放/颜色校正/去噪/CLAHE
  2. 颜色分割参数 - HSV 橙红色阈值/形态学核大小
  3. 检测参数    - 最小轮廓面积/ROI
"""

# ================================================================
# 默认配置
# ================================================================

DEFAULT_CONFIG = {

    # ==========================================
    # 一、预处理参数 (传递给 0.预处理.preprocess)
    # ==========================================

    # -- 缩放 --
    'image_width': 640,         # 处理分辨率 - 宽
    'image_height': 480,        # 处理分辨率 - 高
    'enable_resize': True,      # 是否缩放 (摄像头直出时通常需要)

    # -- 水下颜色校正 --
    'enable_color_correct': True,  # 是否启用水下颜色校正
    'red_boost': 1.2,              # 红色通道增强系数 (>1.0 增强红色)
                                   # 水下红光衰减严重, 适当增强有助于检测橙红色引导线

    # -- 高斯去噪 --
    'enable_gaussian': True,    # 是否启用高斯去噪
    'gaussian_kernel': 5,       # 高斯核大小 (奇数), 越大去噪越强但细节越少

    # -- CLAHE 增强 --
    'enable_clahe': True,       # 是否启用 CLAHE (应对水下光照不均)
    'clahe_clip': 2.0,          # 对比度限幅, 越大对比越强
    'clahe_tile': (8, 8),       # 网格大小, 越小局部性越强

    # ==========================================
    # 二、颜色分割参数
    # ==========================================

    # HSV 橙红色阈值 (OpenCV: H∈[0,179], S∈[0,255], V∈[0,255])
    # 红色在 HSV 中跨 0 度附近, 分两段: [0, low_h] ∪ [high_h, 179]
    # 默认值覆盖了橙-红色范围, 水下实测后需根据实际光照调整
    'hsv_lower': [0, 80, 80],    # 橙红色 HSV 下界 [H, S, V]
    'hsv_upper': [25, 255, 255], # 橙红色 HSV 上界 [H, S, V]

    # 红色第二段 (高H值部分, 跨 180° 边界)
    # 如果引导线偏红而非橙, 启用这段可提高检出率
    'hsv_lower2': [150, 80, 80],
    'hsv_upper2': [179, 255, 255],
    'enable_red_wrap': True,     # 是否启用红色跨边界检测

    # 形态学处理核大小 (用于去噪和连接断线)
    'morph_open_kernel': 3,      # 开运算核大小 (去除小噪点)
    'morph_close_kernel': 7,     # 闭运算核大小 (连接断裂的线段)
                                 # 引导线宽10cm, 在图像中可能因反光/遮挡断裂, 闭运算可弥合

    # ==========================================
    # 三、检测参数
    # ==========================================

    # 最小轮廓面积 (像素²), 小于此值的区域视为噪声
    'min_contour_area': 500,

    # ROI 区域限制 (比例, 相对于图像尺寸)
    # 格式: [y_start_ratio, y_end_ratio, x_start_ratio, x_end_ratio]
    # 例如 [0.2, 0.9, 0.1, 0.9] 表示使用图像 20%~90% 高度, 10%~90% 宽度的区域
    'roi_enabled': False,
    'roi_ratio': [0.2, 0.9, 0.1, 0.9],
}


# ================================================================
# 辅助函数
# ================================================================

def get_config(overrides=None):
    """
    获取配置副本 (避免修改默认配置的引用)

    Args:
        overrides: dict, 需要覆盖的参数 (可选)

    Returns:
        dict: 配置字典的深拷贝

    Usage:
        cfg = get_config({'hsv_lower': [0, 100, 100]})
    """
    import copy
    cfg = copy.deepcopy(DEFAULT_CONFIG)
    if overrides is not None:
        cfg.update(copy.deepcopy(overrides))
    return cfg
