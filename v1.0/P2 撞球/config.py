"""
P2 撞球 - 可配置参数

所有参数集中管理, 便于后续根据实际水下环境调优.
参数分为三组:
  1. 预处理参数    - 图像缩放/颜色校正/去噪/CLAHE (默认关闭, 按需开启)
  2. YOLO 检测参数 - 模型路径/置信度阈值/NMS/推理尺寸/设备
  3. 撞击决策参数  - 目标类别/目标选择策略/转向分区/撞击距离判断
"""

# ================================================================
# 默认配置
# ================================================================

DEFAULT_CONFIG = {

    # ==========================================
    # 一、预处理参数 (传递给 0.预处理.preprocess)
    # ==========================================
    # 按主程序规范, 前置摄像头图像同样进行水下预处理.
    # 若预处理导致 YOLO 检测率明显下降, 可将 enable_preprocess 设为 False.
    # 未列出的键 (缩放/高斯去噪等) 使用 0.预处理 的默认值.

    'enable_preprocess': True,      # 是否在 YOLO 推理前先做水下预处理
    'red_boost': 1.2,               # 红色通道增强 (水下红光衰减补偿)
    'clahe_clip': 2.0,              # CLAHE 对比度限幅

    # ==========================================
    # 二、YOLO 检测参数
    # ==========================================

    # YOLO 模型路径:
    #   - 支持 ultralytics 内置模型名 (如 'yolov8n.pt', 首次使用自动下载)
    #   - 支持本地模型文件 (.pt 等)
    # 撞球任务请替换为训练好的目标球模型
    'model_path': 'yolov8n.pt',

    'device': None,                 # 推理设备: None=自动, 'cpu', '0'(GPU)
    'imgsz': 640,                   # 推理输入尺寸 (像素), 越大越准但越慢
    'conf_threshold': 0.5,          # 置信度阈值, 越低检出越多但误检越多
    'iou_threshold': 0.45,          # NMS 重叠抑制阈值

    # ==========================================
    # 三、撞击决策参数
    # ==========================================

    # 目标球类别: 支持按 类别名 或 类别 id 过滤, 二者满足其一即判定为目标球
    # (模型 names 通常为 dict, 球类别名可能是 'ball'/'red_ball' 等, 按实际填写)
    'target_class_names': ['ball'], # 目标球类别名列表
    'target_class_ids': [],         # 目标球类别 id 列表 (按名称匹配不到时使用)

    # 画面出现多颗球时, 目标选择策略:
    #   'largest' - 取框宽最大 (通常最近) 的球, 逐个撞击时用
    #   'center'  - 取最靠近画面中心的球
    'target_strategy': 'largest',

    # 转向决策: 球心偏差占画面宽度的比例 ≤ 该值时判定为居中 (可直接前进)
    'center_zone_ratio': 0.12,

    # 撞击就绪判断: 球框宽 ≥ 此值 (像素) 且居中时, 认为足够近可直接撞击
    'strike_width_px': 150,

    # 最小检测框宽 (像素), 过滤过小/过远的误检
    'min_detect_width_px': 20,

    # 距离估算 (可选, 基于针孔成像模型: distance = 球实际直径 × 焦距 / 球框宽)
    'enable_distance': True,        # 是否估算目标球距离
    'focal_length_px': 554,         # 相机等效焦距 (像素), 需按实际相机标定
                                    # 参考值: 640宽 + 水平FOV≈60° 时 ≈ 554
    'ball_real_diameter_cm': 10,    # 目标球实际直径 (厘米), 按比赛规则填写
}


# ================================================================
# 辅助函数
# ================================================================

def get_config(overrides=None):
    """
    获取配置副本 (避免修改默认配置的引用)

    Args:
        overrides: dict, 需要覆盖的参数 (可选)

    Returns:
        dict: 配置字典的深拷贝

    Usage:
        cfg = get_config({'conf_threshold': 0.3})
    """
    import copy
    cfg = copy.deepcopy(DEFAULT_CONFIG)
    if overrides is not None:
        cfg.update(copy.deepcopy(overrides))
    return cfg
