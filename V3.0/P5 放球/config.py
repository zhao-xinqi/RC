"""
P5 放球 - 可配置参数

所有参数集中管理, 便于后续根据实际水下环境调优.
参数分为三组:
  1. 预处理参数     - 图像缩放/颜色校正/去噪/CLAHE
  2. 颜色分割参数   - HSV 红色阈值/形态学核大小
  3. 篮筐形判别参数 - 尺寸/宽高比/闭合矩形验证/对齐判定
"""

# ================================================================
# 默认配置
# ================================================================

