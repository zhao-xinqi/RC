"""
P3 穿门 - 可配置参数

门框为红色 "口"形 (正方形/矩形边框, 内部空心), 形状与 P5 篮筐一致,
检测内核直接复用 P5 放球/box_detector.py 的 BoxDetector,
因此本配置使用与 P5 相同的闭合矩形判别参数, 仅按门的尺寸与高/矮门判定做调整.

参数分为三组:
  1. 预处理参数     - 图像缩放/颜色校正/去噪/CLAHE
  2. 颜色分割参数   - HSV 红色阈值/形态学核大小
  3. 门形判别参数   - 尺寸/宽高比/闭合矩形验证/门类型/对齐判定
"""

# ================================================================
# 默认配置
# ================================================================

DEFAULT_CONFIG = {

    # ==========================================
    # 一、预处理参数 (传递给 0.预处理.preprocess)
    # ==========================================

    # -- 缩放 --
    'image_width': 640,         # 处理分辨率 - 宽
    'image_height': 480,        # 处理分辨率 - 高
    'enable_resize': False,     # 是否缩放 (上游已统一到工作分辨率)

    # -- 水下颜色校正 --
    'enable_color_correct': True,  # 是否启用水下颜色校正
    'red_boost': 1.2,              # 红色通道增强系数 (>1.0 增强)

    # -- 高斯去噪 --
    'enable_gaussian': True,    # 是否启用高斯去噪
    'gaussian_kernel': 5,       # 高斯核大小 (奇数)

    # -- CLAHE 增强 --
    'enable_clahe': True,       # 是否启用 CLAHE
    'clahe_clip': 2.0,          # 对比度限幅
    'clahe_tile': (8, 8),       # 网格大小

    # ==========================================
    # 二、颜色分割参数 (红色, 跨 H=0 边界)
    # ==========================================

    # HSV 红色阈值 (OpenCV: H∈[0,179], S∈[0,255], V∈[0,255])
    # 红色跨 H=0° 边界, 分两段合并
    'hsv_lower': [0, 80, 80],   # 主段下界 [H, S, V]
    'hsv_upper': [25, 255, 255],# 主段上界 [H, S, V]
    'hsv_lower2': [150, 80, 80],# 跨边界段下界
    'hsv_upper2': [179, 255, 255],  # 跨边界段上界
    'enable_red_wrap': True,    # 是否启用红色跨边界检测

    # 形态学处理核大小
    'morph_open_kernel': 3,     # 开运算核 (去噪点)
    'morph_close_kernel': 9,    # 闭运算核 (弥合边框断裂)

    # ==========================================
    # 三、门形判别参数 (闭合矩形验证, 复用 P5 逻辑)
    # ==========================================

    # 最小轮廓面积 (像素²), 小于此值视为噪声
    'min_contour_area': 800,

    # 门框外接矩形尺寸范围 (相对图像尺寸的比例)
    # 门框为方形, 靠近时占画面比例较大
    'min_box_width_ratio': 0.15,  # 门宽最小占比
    'max_box_width_ratio': 0.95,  # 门宽最大占比
    'min_box_height_ratio': 0.15, # 门高最小占比
    'max_box_height_ratio': 0.95, # 门高最大占比

    # 宽高比范围 (正方形 → 约 1.0, 透视/倾斜下放宽)
    'min_aspect_ratio': 0.4,
    'max_aspect_ratio': 2.5,

    # 闭合矩形验证 (旋转外接矩形 minAreaRect 边线采样)
    # 门 = "口"形: 四边(顶/底/左/右)全闭合, 内部空心
    'edge_fill_threshold': 0.4,       # 四边各采样边线红色占比 ≥ 此值
    'interior_empty_threshold': 0.3,  # 内部空心: 红色占比 ≤ 此值 (区分实心物)
    'edge_inset_ratio': 0.04,         # 边采样时角点内缩比例 (避开侵蚀/抗锯齿边缘)
    'interior_shrink_ratio': 0.6,     # 内部区域角点收缩比例 (收缩 60% 到中心)

    # 门洞中心对齐判定
    'aligned_ratio': 0.15,  # |门中心归一化偏移| ≤ 此值视为已对齐

    # 摄像头参考中心点：用于计算门中心相对相机中心的偏移
    # 约定：x 右为正，y 上为正；即 dx = 门中心x - camera_center_x，dy = camera_center_y - 门中心y
    'camera_center': (320, 240),

    # 门类型判定 (高门/矮门)
    # 判定依据: 门顶(外接矩形上边)在画面中的归一化 y 位置 (0=顶部, 1=底部)
    #   < threshold → 'high' (门框偏上 = 高门)
    #   ≥ threshold → 'low'  (门框偏下 = 矮门)
    # 说明: 具体物理标准需按现场门架安装方式标定.
    'door_top_norm_threshold': 0.5,
}


# ================================================================
# 辅助函数
# ================================================================

def get_config(overrides=None):
    """
    获取配置副本 (避免修改默认配置的引用)

    Args:
        overrides: dict, 需要覆盖的参数 (可选)

    Returns:
        dict: 配置字典的深拷贝
    """
    import copy
    cfg = copy.deepcopy(DEFAULT_CONFIG)
    if overrides is not None:
        cfg.update(copy.deepcopy(overrides))
    return cfg
